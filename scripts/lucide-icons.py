#!/usr/bin/env python3
"""Generates src/ui/icons.rs: the Lucide icons the window uses, as `rune::Icon`s.

Lucide (https://lucide.dev, ISC licence) is the icon set Hex uses. Add a name
to NAMES, run `python3 scripts/lucide-icons.py`, and use `icons::NAME`.
The SVGs come from the pinned lucide-static release.
"""
import re
import urllib.request

VERSION = "0.468.0"
STROKE = "1.75"  # the stroke width Hex draws Lucide at
NAMES = [
    "activity", "link", "server", "sliders-horizontal", "history", "power",
    "check", "triangle-alert", "unplug", "loader-circle", "link-2-off",
    "refresh-cw", "copy", "file-text", "plus", "x", "trash-2", "pause", "play",
    "bell", "zap", "timer", "languages", "bookmark", "globe", "arrow-right",
    "chevron-down", "chevron-right", "shield-check", "wrench", "external-link",
    "search", "circle-check", "info", "circle-x", "download",
]
SHAPE = re.compile(r"<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\s*/>")
ATTRS = f'fill="none" stroke="currentColor" stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round"'


def body(svg: str) -> str:
    parts = []
    for tag, attrs in SHAPE.findall(svg):
        parts.append(f"<{tag}{' ' + attrs.strip() if attrs.strip() else ''} {ATTRS}/>")
    return "".join(parts)


def main() -> None:
    out = [
        "//! Generated by scripts/lucide-icons.py from lucide-static "
        f"v{VERSION} (ISC licence, https://lucide.dev). Do not edit.",
        "#![allow(dead_code)]",
        "use rune::Icon;",
    ]
    for name in NAMES:
        url = f"https://unpkg.com/lucide-static@{VERSION}/icons/{name}.svg"
        svg = urllib.request.urlopen(url, timeout=30).read().decode()
        shapes = body(svg)
        assert shapes, f"no shapes found in {name}"
        const = name.upper().replace("-", "_")
        out.append(
            f"pub static {const}: Icon = Icon {{\n    name: \"lucide-{name}\",\n    view: 24.0,\n    body: r#\"{shapes}\"#,\n}};"
        )
    with open("src/ui/icons.rs", "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {len(NAMES)} icons")


if __name__ == "__main__":
    main()
